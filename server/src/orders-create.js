/**
 * Task 1 — `orders/create` webhook logic.
 * Generates a random Lorem Ipsum text and stores it in an order metafield
 * (`custom.random_text`, type `multi_line_text_field`, pinned so it shows on the order page).
 */
import { generateLoremIpsum } from "./lorem.js";

export const METAFIELDS_SET_MUTATION = /* GraphQL */ `
  mutation SetOrderRandomText($metafields: [MetafieldsSetInput!]!) {
    metafieldsSet(metafields: $metafields) {
      metafields { id namespace key value }
      userErrors { field message code }
    }
  }
`;

export const DEFINITION_QUERY = /* GraphQL */ `
  query RandomTextDefinition($identifier: MetafieldDefinitionIdentifierInput!) {
    metafieldDefinition(identifier: $identifier) { id pinnedPosition }
  }
`;

export const DEFINITION_CREATE_MUTATION = /* GraphQL */ `
  mutation CreateRandomTextDefinition($definition: MetafieldDefinitionInput!) {
    metafieldDefinitionCreate(definition: $definition) {
      createdDefinition { id pinnedPosition }
      userErrors { field message code }
    }
  }
`;

export const DEFINITION_PIN_MUTATION = /* GraphQL */ `
  mutation PinRandomTextDefinition($definitionId: ID!) {
    metafieldDefinitionPin(definitionId: $definitionId) {
      pinnedDefinition { id pinnedPosition }
      userErrors { field message }
    }
  }
`;

/**
 * Makes sure the order metafield has a *pinned* definition, so the value is shown on the
 * order page in the admin with no manual setup. Runs once per shop (cached in memory).
 *
 * Why not declare it in shopify.app.toml? App-config definitions are hidden from the
 * Metafields settings page and can't be pinned through the API ("Definition is managed by
 * app configuration"), so the value would be saved but invisible on the order page.
 */
export function createDefinitionEnsurer({ admin, config }) {
  const done = new Set();
  const inFlight = new Map();

  async function ensure(shop) {
    const { metafieldNamespace: namespace, metafieldKey: key } = config;
    const { metafieldDefinition: existing } = await admin.graphql(shop, DEFINITION_QUERY, {
      identifier: { ownerType: "ORDER", namespace, key },
    });

    let status = "exists";
    if (!existing) {
      const { metafieldDefinitionCreate: result } = await admin.graphql(shop, DEFINITION_CREATE_MUTATION, {
        definition: {
          name: "Random text",
          description: "Random Lorem Ipsum text generated by the orders/create webhook.",
          namespace,
          key,
          type: "multi_line_text_field",
          ownerType: "ORDER",
          pin: true,
        },
      });
      // TAKEN = created concurrently by another delivery: fine.
      const errors = result.userErrors.filter((e) => e.code !== "TAKEN");
      if (errors.length) throw new Error(`metafieldDefinitionCreate: ${JSON.stringify(errors)}`);
      status = "created";
    } else if (existing.pinnedPosition == null) {
      const { metafieldDefinitionPin: result } = await admin.graphql(shop, DEFINITION_PIN_MUTATION, {
        definitionId: existing.id,
      });
      if (result.userErrors.length) throw new Error(`metafieldDefinitionPin: ${JSON.stringify(result.userErrors)}`);
      status = "pinned";
    }

    done.add(shop);
    return status;
  }

  return function ensureDefinition(shop) {
    if (done.has(shop)) return Promise.resolve("cached");
    if (!inFlight.has(shop)) {
      inFlight.set(shop, ensure(shop).finally(() => inFlight.delete(shop)));
    }
    return inFlight.get(shop);
  };
}

/**
 * @param {{ shop: string, order: any }} input
 * @param {{ admin: { graphql: Function }, config: any, generateText?: () => string }} deps
 */
export async function handleOrderCreated({ shop, order }, { admin, config, generateText = generateLoremIpsum }) {
  const ownerId = order?.admin_graphql_api_id ?? (order?.id ? `gid://shopify/Order/${order.id}` : null);
  if (!ownerId) throw new Error("Webhook payload does not contain an order id");

  const data = await admin.graphql(shop, METAFIELDS_SET_MUTATION, {
    metafields: [
      {
        ownerId,
        namespace: config.metafieldNamespace,
        key: config.metafieldKey,
        type: "multi_line_text_field",
        value: generateText(),
      },
    ],
  });

  const { metafields, userErrors } = data.metafieldsSet;
  if (userErrors.length) {
    throw new Error(`metafieldsSet userErrors: ${JSON.stringify(userErrors)}`);
  }
  return { ownerId, metafield: metafields[0] };
}
